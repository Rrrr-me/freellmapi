#!/usr/bin/env python3
"""
Entry point for Docker container.
Renders a scene script generated by the auto-render pipeline.
"""

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from fact_agent.blender_scenes import (
    SceneConfig,
    SceneType,
    generate_scene_script,
)


def main():
    # Get scene type from environment
    scene_type_str = os.environ.get("SCENE_TYPE", "mystery_forest")
    try:
        scene_type = SceneType(scene_type_str)
    except ValueError:
        print(f"Unknown scene type: {scene_type_str}")
        sys.exit(1)

    # Parse config from environment
    config = SceneConfig(
        frame_start=int(os.environ.get("FRAME_START", "1")),
        frame_end=int(os.environ.get("FRAME_END", "900")),
        resolution_x=int(os.environ.get("RESOLUTION_X", "1920")),
        resolution_y=int(os.environ.get("RESOLUTION_Y", "1080")),
        fps=int(os.environ.get("FPS", "30")),
        engine=os.environ.get("ENGINE", "CYCLES"),
        samples=int(os.environ.get("SAMPLES", "128")),
        device=os.environ.get("DEVICE", "GPU"),
        output_format=os.environ.get("FORMAT", "PNG"),
    )

    # Generate script
    script = generate_scene_script(scene_type, config)

    # Write to file
    script_path = Path("/workspace/scene.py")
    script_path.write_text(script)
    print(f"Generated scene script: {script_path}")

    # Run Blender
    output_dir = Path("/output")
    output_dir.mkdir(parents=True, exist_ok=True)

    import subprocess
    cmd = ["blender", "--background", "--python", str(script_path)]

    print(f"Running Blender: {' '.join(cmd)}")
    result = subprocess.run(cmd, cwd=output_dir)

    if result.returncode == 0:
        print("Render completed successfully")
        sys.exit(0)
    else:
        print(f"Blender failed with exit code {result.returncode}")
        sys.exit(result.returncode)


if __name__ == "__main__":
    main()